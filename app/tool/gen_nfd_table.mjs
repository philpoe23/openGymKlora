// Writes lib/engine/nfd_table.dart: for every BMP code point (Hangul syllables aside, which
// normalize_str decomposes algorithmically) whose `ch.normalize('NFD')` with the combining
// diacritics U+0300–U+036F stripped differs from `ch`, what it becomes. Dart has no Unicode
// normalisation; exercises.dart normalizeStr uses this table to match the JS
// `s.normalize('NFD').replace(/[̀-ͯ]/g, '')`.
// Run from app/: node tool/gen_nfd_table.mjs
import fs from 'node:fs'
const rows = []
for (let c = 0xa0; c <= 0xffff; c++) {
  if (c >= 0xac00 && c <= 0xd7a3) continue
  if (c >= 0xd800 && c <= 0xdfff) continue
  const ch = String.fromCharCode(c)
  const n = ch.normalize('NFD').replace(/[̀-ͯ]/g, '')
  if (n !== ch) rows.push([c, [...n].map(x => x.codePointAt(0))])
}
const lines = rows.map(([c, cps]) => `  0x${c.toString(16)}: [${cps.map(x => '0x' + x.toString(16)).join(', ')}],`)
const out = `// GENERATED by tool/gen_nfd_table.mjs — do not edit.
// Code point → its NFD decomposition with U+0300–U+036F removed (see exercises.dart normalizeStr).

const Map<int, List<int>> nfdStripped = {
${lines.join('\n')}
};
`
fs.writeFileSync(new URL('../lib/engine/nfd_table.dart', import.meta.url), out)
console.log('nfd entries:', rows.length)
